export function getEventById(id) {
  return events.find((e) => e.id === id);
}

export function seatsLeft(event) {
  return Math.max(event.capacity - event.registered, 0);
}

export function occupancyRate(event) {
  return Math.min(event.registered / event.capacity, 1);
}
